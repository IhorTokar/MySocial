-- Індекс для пошуку найближчих за змістом постів: IVFFlat → HNSW.
-- IVFFlat ділить вектори на 100 груп за станом таблиці на момент створення індексу (а створювався він
-- на порожній таблиці) і за замовчуванням переглядає лише одну групу — тобто близько 1% постів,
-- тож пошук за змістом і підказки тегів пропускали більшість справді схожих постів.
-- HNSW — граф «найближчих сусідів», що добудовується з кожним новим постом; він знаходить майже всіх
-- справжніх сусідів і не потребує перебудови після наповнення бази.
DROP INDEX IF EXISTS idx_posts_embedding_cosine;

CREATE INDEX idx_posts_embedding_hnsw
    ON posts USING hnsw (embedding vector_cosine_ops);
