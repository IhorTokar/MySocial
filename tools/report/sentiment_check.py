    ("+", "Пробіг сьогодні десять кілометрів, почуваюся чудово."),
    ("0", "Дочитав детектив: фінал передбачуваний, але загалом непогано."),
    ("-", "Оновлення телефону зламало половину застосунків, дуже дратує."),
